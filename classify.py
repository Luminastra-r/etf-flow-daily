FIXED_INCOME_MARKERS = ["债券", "债", "国债", "信用债", "可转债", "政金债", "城投债"]
COMMODITY_MARKERS = ["黄金", "有色金属", "豆粕", "能源化工", "商品", "原油"]
CURRENCY_MARKERS = ["货币", "现金", "保证金"]


def classify_category(name: str, track_index: str = "", fund_type: str = "") -> str:
    text = f"{name or ''} {track_index or ''}"
    typed = f"{text} {fund_type or ''}"
    if _hit(typed, CURRENCY_MARKERS):
        return "货币"
    if _hit(typed, FIXED_INCOME_MARKERS):
        return "固收"
    if _hit(typed, COMMODITY_MARKERS):
        return "商品"
    if _hit(text, HK_KEYWORDS):
        return "港股"
    if _hit(text, OVERSEAS_KEYWORDS) and not _hit(text, DOMESTIC_MARKERS):
        return "海外"
    if _hit(text, SMART_BETA_KEYWORDS):
        return "Smart Beta"
    if _hit(text, BROAD_KEYWORDS):
        return "宽基"
    if _hit(text, INDUSTRY_MAP.keys()) or any(
        _hit(text, kws) for _, kws in SUBTHEME_RULES.get("行业", [])
    ):
        return "行业"
    return "未分类"


def sub_theme(name: str, category: str, track_index: str = "") -> str:
    text = f"{name or ''} {track_index or ''}"
    for theme, kws in SUBTHEME_RULES.get(category, []):
        if _hit(text, kws):
            return theme
    # 行业兜底再用一次旧 INDUSTRY_MAP
    if category == "行业":
        for kw, ind in INDUSTRY_MAP.items():
            if kw in text:
                return ind
    return "未分类"


def classify_etf(name: str, track_index: str = "", fund_type: str = "") -> tuple[str, str]:
    cat = classify_category(name, track_index, fund_type)
    return cat, sub_theme(name, cat, track_index)


def classify_frame(df, name_col="name", index_col="track_index", type_col="fund_type"):
    """批量打标签，新增 category / sub_industry（=二级主题）两列。"""
    cats, subs = [], []
    has_idx = index_col in df.columns
    has_type = type_col in df.columns
    for _, row in df.iterrows():
        c, s = classify_etf(
            row.get(name_col, ""),
            row.get(index_col, "") if has_idx else "",
            row.get(type_col, "") if has_type else "",
        )
        cats.append(c)
        subs.append(s)
    df = df.copy()
    df["category"] = cats
    df["sub_industry"] = subs
    return df
